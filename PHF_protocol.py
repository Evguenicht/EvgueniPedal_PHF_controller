SUPPORTED_FREQUENCIES_HZ: tuple[int, ...] = tuple(sorted(MOZA_FRAMES))
SUPPORTED_INTENSITIES_PERCENT: tuple[int, ...] = tuple(range(101))

def get_frame(frequency_hz: int, intensity_percent: int) -> bytes:
    """Retourne la trame capturée pour une fréquence et une intensité données."""
    try:
        return MOZA_FRAMES[frequency_hz][intensity_percent]
    except KeyError as exc:
        raise ValueError(
            f"Combinaison non capturée : {frequency_hz} Hz, {intensity_percent} %"
        ) from exc
